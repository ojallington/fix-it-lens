"""The step-check plan: 20 steps x (done, planted not-done, can't-see) x 2 takes = 120 clips, from eval/steps.toml.

    python -m eval.shotlist          # writes eval/shot-list.md and eval/labels/stepcheck.plan.jsonl
    python -m eval.shotlist --check  # fails if either file is stale

The plan is the pre-registration: each clip's truth is fixed here, before any clip is filmed or any model run. The
labelling tool (eval/label/) confirms each filmed clip against it, and a filmed clip that did not come out as
planned is relabelled there with a reason, never silently.
"""

from __future__ import annotations

import json
import sys
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

EVAL = Path(__file__).resolve().parent
STEPS = EVAL / "steps.toml"
SHOT_LIST = EVAL / "shot-list.md"
PLAN = EVAL / "labels" / "stepcheck.plan.jsonl"
POWER_PLAN = EVAL / "labels" / "power.plan.jsonl"
PLUG_FRAMES = 40  # the app's plug-out row: 40 frames plug in, 40 plug out
CONDITIONS = ("done", "not_done", "cant_see")
APPLIANCE_ORDER = ("dishwasher", "washer", "boiler")


@dataclass(frozen=True)
class Step:
    id: str
    appliance: str
    part: str
    done: str
    not_done: str
    guarded: bool  # interim hand flag; eval.stepcheck.guarded takes it from the card once card/card_step are set
    card: str | None = None  # cards/<brand>/<model>.yaml
    card_step: str | None = None
    set: str = "main"  # a clip set in eval.stepcheck.results.SETS; only "main" is in the 120


@dataclass(frozen=True)
class Clip:
    clip_id: str
    step_id: str
    appliance: str
    truth: str
    take: int
    shows: str  # what the camera must show
    cant_see_kind: str | None
    guarded: bool

    def plan_line(self) -> dict[str, object]:
        return {"clip_id": self.clip_id, "step_id": self.step_id, "appliance": self.appliance, "truth": self.truth,
                "take": self.take, "shows": self.shows, "cant_see_kind": self.cant_see_kind,
                "guarded": self.guarded}


def load_steps(path: Path = STEPS) -> tuple[list[Step], dict[str, str], list[str]]:
    data = tomllib.loads(path.read_text())
    steps = [Step(**s) for s in data["step"]]
    ids = [s.id for s in steps]
    if len(set(ids)) != len(ids):
        raise ValueError("duplicate step id in steps.toml")
    return steps, dict(data["take"]), list(data["cant_see"]["kinds"])


def plan(steps: list[Step], kinds: list[str]) -> list[Clip]:
    clips = []
    for i, s in enumerate(steps):
        for take in (1, 2):
            for cond in CONDITIONS:
                kind = kinds[(i + take - 1) % len(kinds)] if cond == "cant_see" else None
                if cond == "done":
                    shows = s.done
                elif cond == "not_done":
                    shows = s.not_done
                else:
                    # alternate the hidden state so can't-see is never a proxy for done or for not-done
                    hidden = s.done if (i + take) % 2 else s.not_done
                    shows = f"{hidden} — but {kind}"
                clips.append(Clip(f"{s.id}.{cond}.t{take}", s.id, s.appliance, cond, take, shows, kind, s.guarded))
    return clips


def render_shot_list(steps: list[Step], takes: dict[str, str], clips: list[Clip], power: Sequence[Step] = (),
                     power_clips: Sequence[Clip] = ()) -> str:
    out = [
        "# Eval shot list: the step check (120 clips)",
        "",
        "Generated by `python -m eval.shotlist` from `eval/steps.toml`; do not edit by hand.",
        "",
        "**Before anything is filmed:** every person whose hands appear has signed the clip consent form",
        "(`eval/consent/`). Film the appliance and hands only: no face, no type plate serial, nothing that shows the",
        "house (window views, post, photos). Never film a running machine near hands. The washer is unplugged and",
        "idle. The gas tap is never touched and never planted.",
        "",
        "**How to film one clip** (the app in capture mode: frames recorded, no model calls):",
        "1. Start a new capture session and say or type the clip id from the table (e.g. `dw.filter_out.done.t1`).",
        "2. Hold still on the part for 1 s in the state *before* the step (this is the BEFORE frame).",
        "3. Do the step, or the planted near-miss, or set up the can't-see condition.",
        "4. Hold the end state steady for 3–6 s. Stop the session.",
        "",
        "If a take comes out differently from the plan (the lug did click after all), film it again, or note it in",
        "the labelling tool: it is relabelled there with the reason, never silently.",
        "",
        "Takes: " + "; ".join(f"**t{k[1:]}** {v}" for k, v in takes.items()) + ".",
        "",
        "About 1 h per appliance. Boiler: plant everything dry; the one real top-up is the `bo.read_target` done clip.",
        "",
    ]
    for app in APPLIANCE_ORDER:
        app_steps = [s for s in steps if s.appliance == app]
        n = sum(1 for c in clips if c.appliance == app)
        out += [f"## {app.capitalize()} ({len(app_steps)} steps, {n} clips)", ""]
        for s in app_steps:
            mark = " (a stop or hold guards this step)" if s.guarded else ""
            out += [f"### `{s.id}`: {s.part}{mark}", "", "| Clip | Truth | The camera shows | ✓ |", "|---|---|---|---|"]
            for c in clips:
                if c.step_id == s.id:
                    out.append(f"| `{c.clip_id}` | {c.truth} | {c.shows} | ☐ |")
            out.append("")
    if power_clips:
        out += ["## Power steps (their own row, not in the 120)", "",
                "The unplug step has no part: the judge is grounded on the plug and the socket, and the camera's",
                "plug-out is the second witness. Plug and socket both in frame unless the clip says otherwise; the",
                "appliance is off and idle.", ""]
        for s in power:
            out += [f"### `{s.id}`: {s.part}", "", "| Clip | Truth | The camera shows | ✓ |", "|---|---|---|---|"]
            out += [f"| `{c.clip_id}` | {c.truth} | {c.shows} | ☐ |" for c in power_clips if c.step_id == s.id]
            out.append("")
        out += ["## Plug frames for the app's plug-out row", "",
                f"One capture session, clip id `plug.frames`: {PLUG_FRAMES} frames with the plug in the socket, then",
                f"{PLUG_FRAMES} with the plug out and in view. Vary the angle, distance and light between frames; the",
                "appliance is off and idle throughout.", ""]
    return "\n".join(out)


def _jsonl(clips: list[Clip]) -> str:
    return "".join(json.dumps(c.plan_line(), ensure_ascii=False) + "\n" for c in clips)


def write(check: bool = False) -> int:
    steps, takes, kinds = load_steps()
    unknown = {s.set for s in steps} - {"main", "power"}
    if unknown:
        raise ValueError(f"steps.toml: unknown set {sorted(unknown)}")
    main = [s for s in steps if s.set == "main"]
    power = [s for s in steps if s.set == "power"]
    clips, power_clips = plan(main, kinds), plan(power, kinds)
    files = {SHOT_LIST: render_shot_list(main, takes, clips, power, power_clips) + "\n", PLAN: _jsonl(clips),
             POWER_PLAN: _jsonl(power_clips)}
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"{p.relative_to(EVAL.parent)} is stale; run python -m eval.shotlist")
        return 1 if stale else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"{len(clips)} clips over {len(main)} steps; power set {len(power_clips)} clips")
    return 0


if __name__ == "__main__":
    sys.exit(write(check="--check" in sys.argv))
